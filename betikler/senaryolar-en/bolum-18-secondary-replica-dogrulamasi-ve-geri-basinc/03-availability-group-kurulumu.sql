-- SQL Server Query Store Handbook, Chapter 18, 'Secondary replica verification and backpressure'
-- Run in a test environment only.

SET NOCOUNT ON;
-- PRIMARY
CREATE DATABASE qs_lab_ag;
ALTER DATABASE qs_lab_ag SET RECOVERY FULL;
ALTER DATABASE qs_lab_ag SET QUERY_STORE = ON (OPERATION_MODE = READ_WRITE, QUERY_CAPTURE_MODE = ALL, INTERVAL_LENGTH_MINUTES = 1, DATA_FLUSH_INTERVAL_SECONDS = 60);
BACKUP DATABASE qs_lab_ag TO DISK = N'C:\qs\qs_lab_ag.bak' WITH INIT, FORMAT;
GO
CREATE AVAILABILITY GROUP qs_ag WITH (CLUSTER_TYPE = NONE)
FOR DATABASE qs_lab_ag
REPLICA ON
 N'BIRINCI_SUNUCU' WITH (ENDPOINT_URL = N'TCP://<IP1>:5022', AVAILABILITY_MODE = SYNCHRONOUS_COMMIT, FAILOVER_MODE = MANUAL, SEEDING_MODE = AUTOMATIC, SECONDARY_ROLE (ALLOW_CONNECTIONS = ALL)),
 N'IKINCI_SUNUCU'  WITH (ENDPOINT_URL = N'TCP://<IP2>:5022', AVAILABILITY_MODE = SYNCHRONOUS_COMMIT, FAILOVER_MODE = MANUAL, SEEDING_MODE = AUTOMATIC, SECONDARY_ROLE (ALLOW_CONNECTIONS = ALL));
GO
-- SECONDARY
ALTER AVAILABILITY GROUP qs_ag JOIN WITH (CLUSTER_TYPE = NONE);
ALTER AVAILABILITY GROUP qs_ag GRANT CREATE ANY DATABASE;
GO
-- PRIMARY, turn on Query Store for the secondary and set capture mode separately
ALTER DATABASE [qs_lab_ag] FOR SECONDARY SET QUERY_STORE = ON (OPERATION_MODE = READ_WRITE, QUERY_CAPTURE_MODE = ALL);
CREATE TABLE qs_lab_ag.dbo.AgIzleme (id int IDENTITY PRIMARY KEY, deger int NOT NULL);
INSERT qs_lab_ag.dbo.AgIzleme (deger) SELECT TOP (100000) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) % 1000 FROM sys.all_objects a CROSS JOIN sys.all_objects b;
