SET NOCOUNT ON;
IF DB_ID('qs_lab_yuk') IS NOT NULL BEGIN ALTER DATABASE qs_lab_yuk SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE qs_lab_yuk; END
GO
CREATE DATABASE qs_lab_yuk;
GO
USE qs_lab_yuk;
CREATE TABLE dbo.t (id int NOT NULL PRIMARY KEY, k int NOT NULL, v char(100) NOT NULL DEFAULT 'x');
INSERT dbo.t (id, k) SELECT TOP (200000) ROW_NUMBER() OVER (ORDER BY (SELECT 1)), ABS(CHECKSUM(NEWID())) % 1000 FROM sys.all_objects a CROSS JOIN sys.all_objects b;
CREATE INDEX ix_k ON dbo.t(k);
GO
CREATE PROCEDURE dbo.p @k int AS BEGIN DECLARE @c int, @m char(100); SELECT @c = COUNT(*), @m = MAX(v) FROM dbo.t WHERE k = @k; END
GO
